"""Program 13: Generate a parse tree using a context-free grammar."""
from nltk import CFG
from nltk.parse import ChartParser

grammar = CFG.fromstring("""
S -> NP VP
NP -> Det N | 'John' | 'Mary'
VP -> V NP | V
Det -> 'the' | 'a'
N -> 'cat' | 'dog' | 'ball'
V -> 'saw' | 'likes' | 'runs'
""")
sentence = input("Enter a sentence (e.g. Mary likes the dog): ").strip() or "Mary likes the dog"
trees = list(ChartParser(grammar).parse(sentence.split()))
if trees:
    for tree in trees:
        print(tree)
        tree.pretty_print()
else:
    print("No parse tree: sentence is not generated by the supplied grammar.")
